import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_HEADER = "// GENERATED by npm run templates:sync, do not edit";

export interface SyncedTemplateFiles {
  templateIds: string[];
  registryIndexContent: string;
  templatePreviewsContent: string;
}

function compareCodePoint(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function toCamelCase(kebab: string): string {
  return kebab.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
}

/**
 * Discovers all template directories under `registry/templates/` in
 * code-point sorted order and returns deterministic LF file contents for
 * `registry/templates/index.ts` and `app/_lib/template-previews.ts`.
 */
export async function buildSyncedTemplateFiles(
  rootDir = process.cwd(),
): Promise<SyncedTemplateFiles> {
  const templatesDir = path.join(rootDir, "registry", "templates");
  const entries = await readdir(templatesDir, { withFileTypes: true });
  const templateIds = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(compareCodePoint);

  for (const id of templateIds) {
    const templateFile = path.join(templatesDir, id, "template.tsx");
    try {
      await readFile(templateFile, "utf8");
    } catch {
      throw new Error(
        `Template directory "registry/templates/${id}" is missing template.tsx.`,
      );
    }
  }

  const indexImports = templateIds
    .map((id) => `import ${toCamelCase(id)}Template from "./${id}/template";`)
    .join("\n");
  const indexArrayItems = templateIds
    .map((id) => `  ${toCamelCase(id)}Template,`)
    .join("\n");

  const registryIndexContent = [
    GENERATED_HEADER,
    "",
    'import type { RegisteredTemplate } from "../lib/define-template";',
    indexImports,
    "",
    "export const allTemplates: readonly RegisteredTemplate[] = [",
    indexArrayItems,
    "];",
    "",
    "export const templatesById: Readonly<Record<string, RegisteredTemplate>> =",
    "  Object.fromEntries(allTemplates.map((template) => [template.id, template]));",
    "",
    "export const templateIds: readonly string[] = allTemplates.map(",
    "  (template) => template.id,",
    ");",
    "",
    "export function getTemplateById(id: string): RegisteredTemplate | undefined {",
    "  return templatesById[id];",
    "}",
    "",
  ].join("\n");

  const previewImports = templateIds
    .map(
      (id) =>
        `import ${toCamelCase(id)}Preview from "@/registry/templates/${id}/preview.png";`,
    )
    .join("\n");
  const previewEntries = templateIds
    .map((id) => {
      const key = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(id) ? id : `"${id}"`;
      return `  ${key}: ${toCamelCase(id)}Preview,`;
    })
    .join("\n");

  const templatePreviewsContent = [
    GENERATED_HEADER,
    "",
    'import type { StaticImageData } from "next/image";',
    'import type { RegisteredTemplate } from "@/registry/lib/define-template";',
    previewImports,
    "",
    "/**",
    " * Explicit static imports of every pre-rendered template `preview.png`.",
    " * Static imports bundle local image assets directly through `next/image`",
    " * without duplicating files into `public/` or hitting `/api/og`.",
    " */",
    "export const TEMPLATE_PREVIEWS: Readonly<Record<string, StaticImageData>> = {",
    previewEntries,
    "};",
    "",
    "export function getTemplatePreview(id: string): StaticImageData | undefined {",
    "  return TEMPLATE_PREVIEWS[id];",
    "}",
    "",
    "export function getTemplatePreviewAlt(template: RegisteredTemplate): string {",
    "  return `${template.name} OG card preview — ${template.description}`;",
    "}",
    "",
  ].join("\n");

  return {
    templateIds,
    registryIndexContent,
    templatePreviewsContent,
  };
}

export async function syncTemplates(
  rootDir = process.cwd(),
): Promise<SyncedTemplateFiles> {
  const synced = await buildSyncedTemplateFiles(rootDir);

  await writeFile(
    path.join(rootDir, "registry", "templates", "index.ts"),
    synced.registryIndexContent,
    "utf8",
  );
  await writeFile(
    path.join(rootDir, "app", "_lib", "template-previews.ts"),
    synced.templatePreviewsContent,
    "utf8",
  );

  return synced;
}

const isCliEntry =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isCliEntry) {
  syncTemplates()
    .then(({ templateIds }) => {
      console.log(
        `Synced ${templateIds.length} templates to registry/templates/index.ts and app/_lib/template-previews.ts: ${templateIds.join(", ")}`,
      );
    })
    .catch((error: unknown) => {
      const message =
        error instanceof Error ? (error.stack ?? error.message) : String(error);
      console.error(message);
      process.exit(1);
    });
}
